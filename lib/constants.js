// ─────────────────────────────────────────────
//   MUNICIPALITY NAME ALIASES
// ─────────────────────────────────────────────
// Two names, one municipality. The Town of Halton Hills is universally called
// Georgetown by buyers (Georgetown is its largest community), the site has a
// page under BOTH names, and TREB's `City` field carries only one of them —
// and from here we cannot see which, because the AMPRE feed is not reachable
// outside production. So nothing may MATCH on one name and silently miss the
// other: the feed request asks for every name in the group, the tax and rent
// tables carry a key for each, and saved-search matching accepts any of them.
//
// This exists instead of the old fix, which relabelled the board's
// 'Halton Hills' as 'Georgetown' in the response mapper. That ran BEFORE the
// rent tier was looked up, so every one of those listings silently fell to the
// 0.90 unknown-city tier instead of 0.95 — understating rent, and with it cash
// flow, cap rate, cash-on-cash and the Deal Score.
//
// First name in a group is the canonical one (used to merge groups when
// aggregating). Add a group only for names that are genuinely the SAME
// municipality — amalgamated districts like Etobicoke or Stoney Creek are
// separate places within a city and keep their own identity.
const CITY_ALIAS_GROUPS = [['Halton Hills', 'Georgetown']];

// Every name this municipality may appear under, including the one passed in.
// Returns a single-element list for the (usual) unaliased city.
export function cityAliases(city) {
  const c = String(city || '').trim();
  if (!c) return [];
  const group = CITY_ALIAS_GROUPS.find((g) => g.includes(c));
  return group ? [...group] : [c];
}

// The one name a group is keyed under when rows are grouped or aggregated, so
// 'Halton Hills' rows and 'Georgetown' rows land in the same bucket.
export function canonicalCity(city) {
  const names = cityAliases(city);
  return names.length ? names[0] : '';
}

