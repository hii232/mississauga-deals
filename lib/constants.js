// Returns the rent multiplier for a city. Mississauga (the flagship) and any
// Mississauga neighbourhood get 1.0 — no change, since those listings estimate
// rent from HOOD_RENTS, not this tier. Unknown GTA cities get 0.90, matching
// the GTA feed's default so cards and detail pages stay consistent.
export function getCityRentTier(city) {
  if (!city) return 1.0;
  const c = city.trim();
  if (CITY_RENT_TIER[c] != null) return CITY_RENT_TIER[c];
  if (c === 'Mississauga' || MISSISSAUGA_HOODS.has(c)) return 1.0;
  return 0.90;
}

