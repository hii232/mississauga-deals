// The district definition for a city name, or null for an ordinary
// municipality (the usual case — callers branch on null).
export function citySubarea(city) {
  const c = String(city || '').trim();
  return (c && CITY_SUBAREAS[c]) || null;
}

// Does an already-mapped listing fall inside this district? Deliberately
// mirrors the OData filter /api/listings-gta builds from the same definition,
// so any surface that has to match rows in memory (saved-search alerts, the
// screener aggregate) selects EXACTLY the rows that district's page loads.
export function listingInSubarea(listing, def) {
  if (!def || !listing) return false;
  if (String(listing.city || '').trim() !== def.parent) return false;
  if (def.postalPrefixes) {
    const pc = String(listing.postalCode || '').toUpperCase().replace(/\s+/g, '');
    return pc ? def.postalPrefixes.some((p) => pc.startsWith(p)) : false;
  }
  if (def.communityPrefixes) {
    // `community` is the board's CityRegion kept verbatim by processListings;
    // `neighbourhood` is the same value on a raw feed row, but is REROUTED to
    // a rent-lookup key by processListings (a Hamilton row lands on
    // 'Hamilton'), so it can only be the fallback.
    const hood = String(listing.community || listing.neighbourhood || '').trim();
    return hood ? def.communityPrefixes.some((p) => hood.startsWith(p)) : false;
  }
  return false;
}

