export function getTaxRate(city) {
  if (!city) return DEFAULT_TAX_RATE;
  const c = city.trim();
  if (TAX_RATES[c]) return TAX_RATES[c];
  // If it's a known Mississauga neighbourhood name, use Mississauga rate
  if (MISSISSAUGA_HOODS.has(c)) return TAX_RATES['Mississauga'];
  return DEFAULT_TAX_RATE;
}

